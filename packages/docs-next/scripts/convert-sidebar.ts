import Path from "node:path";
import Fs from "node:fs/promises";

type DocusaurusItem = string | { label: string; type: "category"; items: DocusaurusItem[] } | { dirName: string; type: "autogenerated" };

export interface VitePressItem {
	text: string;
	link?: string;
	collapsed?: boolean;
	items?: VitePressItem[];
}

/** Docusaurus labels a doc with its first H1. */
async function readTitle(docsDir: string, id: string): Promise<string> {
	const content = await Fs.readFile(Path.join(docsDir, `${id}.md`), "utf-8").catch(() => Fs.readFile(Path.join(docsDir, `${id}.mdx`), "utf-8"));
	const heading = /^# (.+)$/m.exec(content);

	if (!heading) {
		throw new Error(`No H1 in ${id}`);
	}

	return heading[1];
}

async function convertItem(item: DocusaurusItem, docsDir: string): Promise<VitePressItem[]> {
	if (typeof item === "string") {
		return [{ link: `/docs/${item}`, text: await readTitle(docsDir, item) }];
	}

	if (item.type === "autogenerated") {
		// The API reference is generated; its sidebar comes with the generated pages.
		return [];
	}

	return [{ collapsed: true, text: item.label, items: await convertItems(item.items, docsDir) }];
}

async function convertItems(items: DocusaurusItem[], docsDir: string): Promise<VitePressItem[]> {
	return (await Promise.all(items.map((item) => convertItem(item, docsDir)))).flat();
}

/** Loads the Docusaurus sidebar module and ports its "docsSidebar" to a VitePress sidebar. */
export async function convertSidebar(sidebarsFile: string, docsDir: string): Promise<VitePressItem[]> {
	const { default: sidebars } = (await import(sidebarsFile)) as { default: { docsSidebar: DocusaurusItem[] } };

	return convertItems(sidebars.docsSidebar, docsDir);
}
